"""Step 0/1 of the master plan: data provenance lock, data-quality audit, feature layers.

Outputs (all regenerated by `python -m src.data_prep`):
  data/raw/ohlcv_yahoo_adjusted_28tickers.csv      raw price panel supplied by the user (yfinance auto_adjust=True)
  data/raw/vix_daily_cboe_github_datasets.csv      CBOE VIX daily (GitHub: datasets/finance-vix), used by Track A only
  data/manifests/raw_manifest.csv                  SHA-256, rows, date range, source, timestamp for every raw file
  data/features/paper_features_ohlc.csv            standard OHLC indicators (FinRL/stockstats definitions)
  data/features/trackA_finrl_format.csv            the exact file format the authors' script expects (8 indicators, vix, turbulence)
  reports/data_quality.json                        audit results
"""
from __future__ import annotations

import datetime as dt
import hashlib
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd
from stockstats import StockDataFrame as Sdf

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "third_party"))

FINRL_INDICATORS = ["macd", "boll_ub", "boll_lb", "rsi_30", "cci_30", "dx_30", "close_30_sma", "close_60_sma"]
PAPER_INDICATORS = ["macd", "rsi_30", "cci_30", "dx_30"]


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def compute_indicators(df: pd.DataFrame, indicators: list[str]) -> pd.DataFrame:
    """Per-ticker stockstats indicators on OHLCV (same definitions as FinRL). df: long format with date,tic,o,h,l,c,v."""
    out = []
    for tic, g in df.groupby("tic", sort=True):
        g = g.sort_values("date").reset_index(drop=True)
        s = Sdf.retype(g[["open", "high", "low", "close", "volume"]].copy())
        for ind in indicators:
            g[ind] = s[ind].values
        out.append(g)
    return pd.concat(out, ignore_index=True).sort_values(["date", "tic"]).reset_index(drop=True)


def indicator_arrays(open_, high_, low_, close_, volume_, tickers, dates, indicators) -> dict[str, np.ndarray]:
    """Same indicators from (T,N) arrays (used for real panels AND digital-twin panels -> identical code path)."""
    idx = pd.DatetimeIndex(pd.to_datetime(dates))
    res = {k: np.zeros(close_.shape) for k in indicators}
    for j, tic in enumerate(tickers):
        g = pd.DataFrame({"open": open_[:, j], "high": high_[:, j], "low": low_[:, j], "close": close_[:, j],
                          "volume": volume_[:, j]}, index=idx)
        s = Sdf.retype(g)
        for k in indicators:
            res[k][:, j] = s[k].values
    return res


def audit(raw: pd.DataFrame) -> dict:
    rep: dict = {}
    rep["rows"] = int(len(raw))
    rep["tickers"] = sorted(raw["tic"].unique().tolist())
    rep["n_tickers"] = len(rep["tickers"])
    rep["date_min"], rep["date_max"] = str(raw["date"].min().date()), str(raw["date"].max().date())
    rep["duplicate_date_tic_keys"] = int(raw.duplicated(["date", "tic"]).sum())
    rep["nan_cells"] = int(raw[["open", "high", "low", "close", "volume"]].isna().sum().sum())
    rep["nonpositive_prices"] = int((raw[["open", "high", "low", "close"]] <= 0).sum().sum())
    rep["zero_volume_rows"] = int((raw["volume"] <= 0).sum())
    tol = 1e-6
    rep["high_lt_max_open_close"] = int((raw["high"] < raw[["open", "close"]].max(axis=1) - tol).sum())
    rep["low_gt_min_open_close"] = int((raw["low"] > raw[["open", "close"]].min(axis=1) + tol).sum())
    per = raw.groupby("date")["tic"].count()
    rep["dates"] = int(per.shape[0])
    rep["dates_with_all_tickers"] = int((per == rep["n_tickers"]).sum())
    rep["first_date_per_ticker"] = {t: str(d.date()) for t, d in raw.groupby("tic")["date"].min().items()}
    ret = raw.sort_values(["tic", "date"]).groupby("tic")["close"].pct_change()
    rep["max_abs_daily_return"] = float(ret.abs().max())
    rep["n_abs_return_gt_25pct"] = int((ret.abs() > 0.25).sum())
    rep["missing_vs_dow30"] = ["DOW", "WBA"] if {"DOW", "WBA"}.isdisjoint(rep["tickers"]) else []
    rep["price_convention"] = "yfinance auto_adjust=True (split+dividend adjusted OHLC)"
    return rep


def main():
    from finrl.meta.preprocessor.preprocessors import FeatureEngineer

    (ROOT / "reports").mkdir(exist_ok=True)
    src = ROOT / "data" / "full_data.csv"
    d = pd.read_csv(src)
    d["date"] = pd.to_datetime(d["date"])
    raw = d[["date", "tic", "open", "high", "low", "close", "volume"]].sort_values(["date", "tic"]).reset_index(drop=True)
    raw_path = ROOT / "data" / "raw" / "ohlcv_yahoo_adjusted_28tickers.csv"
    raw.assign(date=raw["date"].dt.strftime("%Y-%m-%d")).to_csv(raw_path, index=False)

    rep = audit(raw)
    # consistency of the user-supplied indicator columns vs recomputation from OHLCV
    chk = compute_indicators(raw, PAPER_INDICATORS)
    mer = chk.merge(d[["date", "tic"] + PAPER_INDICATORS], on=["date", "tic"], suffixes=("", "_user"))
    rep["indicator_recompute_max_abs_diff"] = {k: float((mer[k] - mer[k + "_user"]).abs().max()) for k in PAPER_INDICATORS}

    # ---- feature layer 1: standard OHLC indicators
    feat = compute_indicators(raw, FINRL_INDICATORS)
    feat.assign(date=feat["date"].dt.strftime("%Y-%m-%d")).to_csv(ROOT / "data/features/paper_features_ohlc.csv", index=False)

    # ---- feature layer 2: Track A file in the exact format of the authors' script
    ta = raw.copy()
    ta["date"] = ta["date"].dt.strftime("%Y-%m-%d")
    ta["day"] = pd.to_datetime(ta["date"]).dt.dayofweek
    fe = FeatureEngineer(use_technical_indicator=True, tech_indicator_list=FINRL_INDICATORS, use_vix=False,
                         use_turbulence=True, user_defined_feature=False)
    proc = fe.preprocess_data(ta)
    vix = pd.read_csv(ROOT / "data/raw/vix_daily_cboe_github_datasets.csv")
    vix["date"] = pd.to_datetime(vix["DATE"]).dt.strftime("%Y-%m-%d")
    vmap = vix.set_index("date")["CLOSE"]
    proc["vix"] = proc["date"].map(vmap)
    rep["vix_missing_dates_after_merge"] = int(proc["vix"].isna().sum())
    proc["vix"] = proc["vix"].ffill()
    proc = proc.copy().fillna(0).replace(np.inf, 0)      # same post-processing as the authors' script
    proc.to_csv(ROOT / "data/features/trackA_finrl_format.csv")   # index kept, as the authors' script does
    rep["trackA_rows"] = int(len(proc))
    rep["trackA_columns"] = list(proc.columns)

    # ---- manifest
    man = []
    now = dt.datetime.now(dt.timezone.utc).isoformat(timespec="seconds")
    for p, source in [
        (raw_path, "yfinance auto_adjust=True, 28 DJIA tickers, downloaded by the user in Colab with margin_trader_dataset.ipynb"),
        (ROOT / "data/raw/vix_daily_cboe_github_datasets.csv", "CBOE VIX daily via github.com/datasets/finance-vix (fetched in sandbox)"),
    ]:
        df_ = pd.read_csv(p)
        man.append(dict(file=str(p.relative_to(ROOT)), sha256=sha256(p), rows=len(df_), source=source, recorded_utc=now))
    man.append(dict(file="third_party/margin_trader (authors code)", sha256="commit 7b7fa9e89d8c202b80778b4f1fa82353841cfd52",
                    rows=0, source="github.com/JingyiGu/Margin-Trader (MIT)", recorded_utc=now))
    pd.DataFrame(man).to_csv(ROOT / "data/manifests/raw_manifest.csv", index=False)
    json.dump(rep, open(ROOT / "reports/data_quality.json", "w"), indent=2)
    print(json.dumps({k: v for k, v in rep.items() if k not in ("first_date_per_ticker", "trackA_columns", "tickers")}, indent=1))


if __name__ == "__main__":
    main()
